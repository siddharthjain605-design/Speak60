// it lives in lib/storage.ts so this file can be re-shipped without wiping history.

export type Difficulty = 1 | 2 | 3 | 4 | 5;
export type TopicType = 'knowledge' | 'opinion' | 'abstract' | 'hypothetical';

export interface RawTopic {
  text: string;
  category: string;
  subcategory: string;
  difficulty: Difficulty;
  type: TopicType;
}

type Row = [string, Difficulty, TopicType, string?];

function cat(category: string, rows: Row[], defaultSub = 'General'): RawTopic[] {
  return rows.map(([text, difficulty, type, subcategory]) => ({
    text,
    category,
    subcategory: subcategory ?? defaultSub,
    difficulty,
    type,
  }));
}

